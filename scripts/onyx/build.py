def all_pages(out):
    n = 0
    for f in glob.glob(os.path.join(out, '**', '*.html'), recursive=True):
        if '/assets/video' in f: continue
        s = open(f, encoding='utf-8', errors='ignore').read(); o = s
        s = re.sub(r'(<meta name="theme-color" content=")[^"]*(")', r'\g<1>#050506\2', s)
        s = re.sub(r'<img src="/assets/logo\.svg"[^>]*>', LOGO_IMG, s)
        s = home.swap_icons(s)
        s = re.sub(r'(📞|📅)️?\s*', '', s)
        s = re.sub(r'&#(?:128222|128197|x1F4DE|x1F4C5);\s*', '', s, flags=re.I)   # same icons written as entities
        s = s.replace("Enrollment is OPEN now — don\\'t wait until the deadline.", 'Enrollment is open now. Changes take effect January 1.')   # no urgency wording
        if 'class="hb-burger"' not in s:   # phone and tablet menu button
            s = s.replace('<nav class="menu sans">', '<nav class="menu sans" id="hbMenu">', 1)
            s = re.sub(r'(<div class="nav-right">.*?)(</div>\s*</div>\s*</header>)', lambda m: m.group(1) + BURGER + m.group(2), s, count=1, flags=re.S)
            s = s.replace('</body>', '<script src="/assets/hb-nav.js?v=%s" defer></script>\n</body>' % VER, 1)
        if '/schedule-an-appointment">How scheduling works' not in s:   # footer link to the booking guide
            s = s.replace('<a href="/#contact">Request a callback</a>', '<a href="/#contact">Request a callback</a>\n        <a href="/schedule-an-appointment">How scheduling works</a>', 1)
        if '/mortgage-protection-insurance">Mortgage protection' not in s:   # menu and footer links to the mortgage protection page
            s = s.replace('<a href="/term-life-insurance">Term life</a>', '<a href="/term-life-insurance">Term life</a>\n        <a href="/mortgage-protection-insurance">Mortgage protection</a>', 1)
            s = s.replace('<a href="/term-life-insurance">Term Life</a>', '<a href="/term-life-insurance">Term Life</a>\n        <a href="/mortgage-protection-insurance">Mortgage Protection</a>', 1)
        slug = os.path.basename(f)[:-5]
        for a, b in CLEAN.get(slug, []) + CLEAN_ALL:
            s = s.replace(a, b)
        if slug == 'final-expense-life-insurance':   # sample prices with no source: removed
            s = re.sub(r'\n[ \t]*<h2>Sample monthly rates</h2>.*?(?=\n[ \t]*<h2)', '', s, count=1, flags=re.S)
        if os.path.dirname(f) == out: s = merge_pr3.page_pass(slug, s)   # menu links to the new pages, quote forms
        bk = book_for(slug) if os.path.dirname(f) == out else None
        if bk and 'class="hb-book"' not in s and '<section class="page-hero"' in s:
            title, items = bk
            art = s.find('<article')
            h2 = [m.start() for m in re.finditer(r'<h2', s[art:])] if art > 0 else []
